#!/usr/bin/env python3
# Build stamp for the panel's web portal.
#
# The portal shows where a firmware image came from: the tag when the build ran
# on a tagged commit, the short commit otherwise, and a -dirty suffix when the
# working tree had uncommitted changes. The value goes into include/BuildStamp.h
# and is rewritten only when it changes, so an unchanged checkout does not
# rebuild everything.
#
# A release build sets HEMS_BUILD_STAMP (tools/pack_web_install.sh does), because
# the release commit and its tag are made after the binaries are packed.
#
# SPDX-License-Identifier: MIT

import os
import re
import subprocess

try:
    ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
except NameError:
    # PlatformIO's SCons runs extra scripts with exec(), where __file__ does not
    # exist. It starts the build in the project directory, which is the root
    # this needs.
    ROOT = os.getcwd()
OUT = os.path.join(ROOT, "include", "BuildStamp.h")
VERSION_H = os.path.join(ROOT, "include", "FirmwareVersion.h")


def run(*args):
    try:
        return subprocess.run(("git",) + args, cwd=ROOT, capture_output=True,
                              text=True, timeout=10)
    except (OSError, subprocess.SubprocessError):
        return None


def from_version_header():
    """A source tree without .git still has the release number."""
    try:
        with open(VERSION_H, encoding="utf-8") as fh:
            text = fh.read()
    except OSError:
        return "unknown"
    match = re.search(r'^#define\s+HEMS_FW_VERSION\s+"([^"]*)"', text, re.M)
    return "v" + match.group(1) if match else "unknown"


def stamp():
    override = os.environ.get("HEMS_BUILD_STAMP", "").strip()
    if override:
        return override

    tag = run("describe", "--tags", "--exact-match", "HEAD")
    if tag is not None and tag.returncode == 0 and tag.stdout.strip():
        value = tag.stdout.strip()
    else:
        sha = run("rev-parse", "--short", "HEAD")
        if sha is None or sha.returncode != 0 or not sha.stdout.strip():
            return from_version_header()
        value = sha.stdout.strip()

    # Untracked files (the generated header, .pio) are build output, not
    # changes; --untracked-files=no keeps them out of the dirty test.
    dirty = run("status", "--porcelain", "--untracked-files=no")
    if dirty is not None and dirty.returncode == 0 and dirty.stdout.strip():
        value += "-dirty"
    return value


def main():
    value = stamp()
    content = (
        "// Generated by tools/build_stamp.py - do not edit.\n"
        "// Tag, short commit, or commit-dirty; shown in the panel's web portal.\n"
        "#pragma once\n"
        '#define HEMS_BUILD_STAMP "%s"\n' % value
    )
    try:
        with open(OUT, encoding="utf-8") as fh:
            if fh.read() == content:
                return 0
    except OSError:
        pass
    with open(OUT, "w", encoding="utf-8") as fh:
        fh.write(content)
    print("Build stamp: %s" % value)
    return 0


# Called unconditionally: PlatformIO's SCons exec()s extra scripts, so there is
# no __main__ guard to rely on. Running the file directly does the same.
main()
